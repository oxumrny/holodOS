    static func detect(from name: String) -> String {
        let normalized = name.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()

        for rule in rules {
            if rule.keywords.contains(where: { normalized.contains($0) }) {
                return rule.category
            }
        }

        return "прочее"
    }
